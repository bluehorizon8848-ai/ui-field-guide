export const ui: Record<Locale, UI> = { zh, en };

/**
 * 取文案并做 {n} / {m} 插值。
 * 键不存在时返回键名本身——这样漏翻会立刻显形，而不是静默渲染出空白。
 */
export function t(locale: Locale, key: UIKey, vars?: Record<string, string | number>): string {
  let out: string = ui[locale][key] ?? ui.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

/**
 * searchPatterns 的 matchedBy 是数据层写死的中文标签（「英文名」「口语描述」…）。
 * 那份数据不能改，所以按标签原文查表换成当前语言——SearchBar 和 SearchClient 共用这张表，
 * 免得两处各写一份映射、改一处忘另一处。
 *
 * 查不到就原样返回：新增匹配维度时最多显示英文原文，不会渲染出空白。
 */
const MATCHED_BY: Record<string, UIKey> = {
  英文名: 'search.byName',
  中文名: 'search.byZhName',
  一句话解释: 'search.byDesc',
  场景描述: 'search.byScenario',
  详细解释: 'search.byDetail',
  标签: 'search.byTag',
  别名: 'search.byAlias',
  口语描述: 'search.byColloquial',
};

export function matchedByLabel(locale: Locale, matchedBy: string): string {
  const key = MATCHED_BY[matchedBy];
  return key ? t(locale, key) : matchedBy;
}